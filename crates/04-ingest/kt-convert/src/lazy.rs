//! Routed experts built on demand from a checkpoint, under a memory budget (for lazy workers and a streamed
//! reference). Quantization is a pure function of a tensor's bytes, so an expert built, evicted and built again has
//! the same codes: the budget changes when an expert is built, never what it computes.
//!
//! An expert is `model.layers.{layer}.mlp.experts.{e}.{gate,up,down}_proj.weight`, the naming of OLMoE, Qwen-MoE and
//! GLM-4.5.

use kt_core::layers::{QuantLinear, SwiGluMlp};
use kt_core::plugin::ModelSource;
use std::collections::HashMap;

/// Build expert `e` of `layer` from `src`: `hidden` is the expert's width, `dim` the model's.
pub fn build_expert(src: &dyn ModelSource, layer: usize, e: usize, hidden: usize, dim: usize) -> SwiGluMlp {
    let p = format!("model.layers.{layer}.mlp.experts.{e}");
    let get = |leaf: &str, rows: usize, cols: usize| -> Vec<f32> {
        let name = format!("{p}.{leaf}.weight");
        let (t, s) = src.tensor(&name).unwrap_or_else(|| panic!("missing {name}"));
        assert_eq!(s, vec![rows, cols], "{name} shape");
        t
    };
    SwiGluMlp::new(
        format!("l{layer}.e{e}"),
        QuantLinear::from_weights("gate", &get("gate_proj", hidden, dim), hidden, dim),
        QuantLinear::from_weights("up", &get("up_proj", hidden, dim), hidden, dim),
        QuantLinear::from_weights("down", &get("down_proj", dim, hidden), dim, hidden),
    )
}

/// The experts a node holds, built when first asked for and evicted least-recently-used beyond `budget` bytes of
/// codes. A budget of 0 holds nothing: every request builds its expert again.
pub struct ExpertCache<'a> {
    src: &'a dyn ModelSource,
    hidden: usize,
    dim: usize,
    budget: u64,
    held: HashMap<(usize, usize), (SwiGluMlp, u64)>,
    clock: u64,
    /// Experts built (including the warm-up) and requests served from the cache.
    pub builds: u64,
    pub hits: u64,
}

impl<'a> ExpertCache<'a> {
    pub fn new(src: &'a dyn ModelSource, hidden: usize, dim: usize, budget_bytes: u64) -> Self {
        ExpertCache { src, hidden, dim, budget: budget_bytes, held: HashMap::new(), clock: 0, builds: 0, hits: 0 }
    }

    /// The bytes of one expert's codes: three `hidden × dim` matrices, one `i32` per weight.
    pub fn expert_bytes(&self) -> u64 {
        3 * (self.hidden * self.dim) as u64 * 4
    }

    /// The bytes of the codes held now.
    pub fn held_bytes(&self) -> u64 {
        self.held.len() as u64 * self.expert_bytes()
    }

    /// Build experts in `order` while the next one still fits the budget (the warm-up before serving).
    pub fn warm(&mut self, order: impl IntoIterator<Item = (usize, usize)>) {
        for (layer, e) in order {
            if self.held_bytes() + self.expert_bytes() > self.budget {
                break;
            }
            self.get(layer, e);
        }
    }

    /// Expert `e` of `layer`, and whether this request built it.
    pub fn get(&mut self, layer: usize, e: usize) -> (&SwiGluMlp, bool) {
        self.clock += 1;
        let now = self.clock;
        let built = !self.held.contains_key(&(layer, e)) || self.budget == 0;
        if built {
            // make room: least recently used first; with a budget of 0, nothing stays
            let need = self.expert_bytes();
            while !self.held.is_empty() && (self.budget == 0 || self.held_bytes() + need > self.budget) {
                let lru = *self.held.iter().min_by_key(|(_, (_, t))| *t).map(|(k, _)| k).expect("non-empty");
                self.held.remove(&lru);
            }
            let x = build_expert(self.src, layer, e, self.hidden, self.dim);
            self.held.insert((layer, e), (x, now));
            self.builds += 1;
        } else {
            self.hits += 1;
        }
        let slot = self.held.get_mut(&(layer, e)).expect("held");
        slot.1 = now;
        (&slot.0, built)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use kt_core::{IntTensor, Module};

    /// Two layers of four tiny experts, generated by name.
    struct Mock;
    impl ModelSource for Mock {
        fn hf_arch_ids(&self) -> Vec<String> {
            vec![]
        }
        fn config_usize(&self, _: &str) -> Option<usize> {
            None
        }
        fn config_f64(&self, _: &str) -> Option<f64> {
            None
        }
        fn tensor(&self, name: &str) -> Option<(Vec<f32>, Vec<usize>)> {
            let shape = if name.ends_with("down_proj.weight") { vec![8, 6] } else { vec![6, 8] };
            let seed = name.bytes().fold(7u64, |h, b| h.wrapping_mul(31).wrapping_add(b as u64));
            let v = (0..48).map(|i| ((seed.wrapping_add(i * 2654435761) % 1000) as f32 - 500.0) / 2000.0).collect();
            Some((v, shape))
        }
    }

    fn out(x: &SwiGluMlp) -> Vec<i32> {
        x.forward_int(&IntTensor::from_reals(&[0.5, -0.25, 0.75, 0.1, -0.6, 0.3, 0.2, -0.9], vec![1, 8], 1 << 20)).data
    }

    #[test]
    fn a_rebuilt_expert_computes_what_a_held_one_does_and_the_budget_bounds_what_is_held() {
        let src = Mock;
        let want: Vec<Vec<i32>> = (0..8).map(|k| out(&build_expert(&src, k / 4, k % 4, 6, 8))).collect();
        for budget_experts in [0u64, 1, 3, 8] {
            let mut c = ExpertCache::new(&src, 6, 8, budget_experts * 3 * 48 * 4);
            c.warm((0..2).flat_map(|l| (0..4).map(move |e| (l, e))));
            for k in [0usize, 5, 0, 7, 3, 5, 5, 1, 6, 0] {
                let (x, _) = c.get(k / 4, k % 4);
                assert_eq!(out(x), want[k], "budget {budget_experts}: expert {k}");
                assert!(c.held_bytes() <= (budget_experts.max(1)) * c.expert_bytes());
            }
            if budget_experts == 0 {
                assert_eq!(c.hits, 0, "a budget of 0 rebuilds every request");
            }
            if budget_experts == 8 {
                assert_eq!(c.builds, 8, "everything warm: nothing is built after the warm-up");
            }
        }
    }
}
